using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;

namespace hds.Game.Abilities
{
    /// <summary>A passive bonus an ability grants while it is loaded (e.g. HyperJump: SuperJump +3 per level).</summary>
    public sealed class AbilityBonusDefinition
    {
        public AbilityBonusDefinition(ushort sourceAbility, ushort targetAbility, byte flags, float valueScale, int minValue, float duration)
        {
            SourceAbility = sourceAbility;
            TargetAbility = targetAbility;
            Flags = flags;
            ValueScale = valueScale;
            MinValue = minValue;
            Duration = duration;
        }

        public ushort SourceAbility { get; }
        public ushort TargetAbility { get; }
        /// <summary>First byte of the bonus RPC as the original server sent it for this bonus.</summary>
        public byte Flags { get; }
        public float ValueScale { get; }
        public int MinValue { get; }
        public float Duration { get; }

        /// <summary>floor(ValueScale * level) + MinValue - the formula of the StatModifier game objects.</summary>
        public int ValueAt(int level) => (int) Math.Floor(ValueScale * level + 1e-6) + MinValue;
    }

    /// <summary>Passive ability bonuses from data/ability_bonuses.txt (generated by tools/ability_bonus_gen.py).</summary>
    public sealed class AbilityBonusCatalog
    {
        private static readonly IReadOnlyList<AbilityBonusDefinition> None = Array.Empty<AbilityBonusDefinition>();
        private readonly Dictionary<ushort, List<AbilityBonusDefinition>> bySource = new Dictionary<ushort, List<AbilityBonusDefinition>>();
        private static AbilityBonusCatalog instance;

        public static AbilityBonusCatalog Instance =>
            instance ??= File.Exists(hds.Core.ServerPaths.Data("ability_bonuses.txt"))
                ? Load(hds.Core.ServerPaths.Data("ability_bonuses.txt"))
                : new AbilityBonusCatalog();

        public static void SetInstance(AbilityBonusCatalog catalog) => instance = catalog;

        public int Count { get; private set; }

        public static AbilityBonusCatalog Load(string path)
        {
            using var reader = new StreamReader(path);
            return Parse(reader);
        }

        public static AbilityBonusCatalog Parse(TextReader reader)
        {
            var catalog = new AbilityBonusCatalog();
            string line;
            while ((line = reader.ReadLine()) != null)
            {
                if (line.Length == 0 || line[0] == '#') continue;
                var p = line.Split('\t');
                var bonus = new AbilityBonusDefinition(
                    ushort.Parse(p[0]), ushort.Parse(p[1]), byte.Parse(p[2], NumberStyles.HexNumber),
                    float.Parse(p[3], CultureInfo.InvariantCulture), int.Parse(p[4]), float.Parse(p[5], CultureInfo.InvariantCulture));
                catalog.Add(bonus);
            }
            return catalog;
        }

        public void Add(AbilityBonusDefinition bonus)
        {
            if (!bySource.TryGetValue(bonus.SourceAbility, out var list))
            {
                list = new List<AbilityBonusDefinition>();
                bySource[bonus.SourceAbility] = list;
            }
            list.Add(bonus);
            Count++;
        }

        public IReadOnlyList<AbilityBonusDefinition> For(ushort abilityId) =>
            bySource.TryGetValue(abilityId, out var list) ? list : None;
    }
}
