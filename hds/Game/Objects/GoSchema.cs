using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace hds.Game.Objects
{
    /// <summary>One attribute of a game object class as it appears on the wire.</summary>
    public sealed class GoAttributeDef
    {
        public GoAttributeDef(int id, string name, string type, int size)
        {
            Id = id;
            Name = name;
            Type = type;
            Size = size;
        }

        /// <summary>Attribute id inside its class (from gameobjects.gob).</summary>
        public int Id { get; }
        public string Name { get; }
        public string Type { get; }
        /// <summary>Fixed size in bytes (strings: maximum size).</summary>
        public int Size { get; }

        /// <summary>Strings are fixed size on creation but length prefixed in update tables.</summary>
        public bool IsString => Type.StartsWith("GOString", StringComparison.Ordinal);

        public override string ToString() => $"{Name}({Type},{Size})";
    }

    /// <summary>Attribute layout of one attribute class, used for creation and update serialization.</summary>
    public sealed class GoClassSchema
    {
        private readonly Dictionary<string, int> createIndex;
        private readonly Dictionary<string, int> updateIndex;

        public GoClassSchema(string key, IReadOnlyList<GoAttributeDef> create, IReadOnlyList<GoAttributeDef> update)
        {
            Key = key;
            Create = create;
            Update = update;
            createIndex = BuildIndex(create);
            updateIndex = BuildIndex(update);
        }

        private static Dictionary<string, int> BuildIndex(IReadOnlyList<GoAttributeDef> list)
        {
            var index = new Dictionary<string, int>(StringComparer.Ordinal);
            for (var i = 0; i < list.Count; i++)
            {
                index.TryAdd(list[i].Name, i);
            }
            return index;
        }

        public string Key { get; }
        public IReadOnlyList<GoAttributeDef> Create { get; }
        public IReadOnlyList<GoAttributeDef> Update { get; }

        public int CreateIndexOf(string name) => createIndex.TryGetValue(name, out var i) ? i : -1;
        public int UpdateIndexOf(string name) => updateIndex.TryGetValue(name, out var i) ? i : -1;
        public bool HasAttribute(string name) => createIndex.ContainsKey(name);
    }

    public sealed class GoTypeInfo
    {
        public GoTypeInfo(ushort goId, string name, GoClassSchema schema)
        {
            GoId = goId;
            Name = name;
            Schema = schema;
        }

        public ushort GoId { get; }
        public string Name { get; }
        public GoClassSchema Schema { get; }
    }

    /// <summary>
    /// All game object types with their attribute layouts. Loaded from data/goschema.txt
    /// which is generated by tools/goschema_gen.py from the gameobjects.gob dump.
    /// </summary>
    public sealed class GoSchemaRegistry
    {
        private readonly Dictionary<ushort, GoTypeInfo> types = new Dictionary<ushort, GoTypeInfo>();
        private readonly Dictionary<string, GoTypeInfo> typesByName = new Dictionary<string, GoTypeInfo>(StringComparer.Ordinal);

        private static GoSchemaRegistry instance;

        /// <summary>Global registry, loaded lazily from data/goschema.txt.</summary>
        public static GoSchemaRegistry Instance => instance ??= Load(hds.Core.ServerPaths.Data("goschema.txt"));

        public static void SetInstance(GoSchemaRegistry registry) => instance = registry;

        public int Count => types.Count;

        public static GoSchemaRegistry Load(string path)
        {
            using var reader = new StreamReader(path);
            return Parse(reader);
        }

        public static GoSchemaRegistry Parse(TextReader reader)
        {
            var registry = new GoSchemaRegistry();
            var classes = new Dictionary<string, (List<GoAttributeDef> create, List<GoAttributeDef> update)>();
            (List<GoAttributeDef> create, List<GoAttributeDef> update) current = default;
            var gos = new List<(ushort id, string key, string name)>();

            string line;
            var lineNumber = 0;
            while ((line = reader.ReadLine()) != null)
            {
                lineNumber++;
                if (line.Length == 0 || line[0] == '#') continue;
                var parts = line.Split('\t');
                switch (parts[0])
                {
                    case "CLASS":
                        current = (new List<GoAttributeDef>(), new List<GoAttributeDef>());
                        classes[parts[1]] = current;
                        break;
                    case "C":
                    case "U":
                        if (current.create == null) throw new InvalidDataException($"goschema line {lineNumber}: attribute before CLASS");
                        var def = new GoAttributeDef(int.Parse(parts[1]), parts[2], parts[3], int.Parse(parts[4]));
                        (parts[0] == "C" ? current.create : current.update).Add(def);
                        break;
                    case "GO":
                        var goId = int.Parse(parts[1]);
                        if (goId <= ushort.MaxValue)
                        {
                            gos.Add(((ushort) goId, parts[2], parts.Length > 3 ? parts[3] : string.Empty));
                        }
                        break;
                    default:
                        throw new InvalidDataException($"goschema line {lineNumber}: unknown record '{parts[0]}'");
                }
            }

            var schemas = classes.ToDictionary(c => c.Key, c => new GoClassSchema(c.Key, c.Value.create, c.Value.update));
            foreach (var (id, key, name) in gos)
            {
                if (!schemas.TryGetValue(key, out var schema)) continue;
                var info = new GoTypeInfo(id, name, schema);
                registry.types[id] = info;
                registry.typesByName.TryAdd(name, info);
            }
            return registry;
        }

        public bool TryGet(ushort goId, out GoTypeInfo info) => types.TryGetValue(goId, out info);

        public GoTypeInfo Get(ushort goId)
        {
            if (!types.TryGetValue(goId, out var info))
            {
                throw new KeyNotFoundException($"Unknown game object type {goId}");
            }
            return info;
        }

        public bool TryGetByName(string name, out GoTypeInfo info) => typesByName.TryGetValue(name, out info);
    }
}
