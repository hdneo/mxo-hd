"""
Builds data/goschema.txt from the parsed gameobjects.gob dump (AI_Context/create_update).

The dump contains one file per GoID for creation and one for update. Each file lists the
attribute class that is used on the wire ("#USING <classId>") and its attributes in the exact
order they are serialized in the 03 view protocol.

Output format (tab separated):
    CLASS <classKey>
    C <attrId> <name> <type> <size>      creation attribute (wire order)
    U <attrId> <name> <type> <size>      update attribute (wire order)
    GO <goId> <classKey> <name>

A class key is the numeric class id, or "<classId>.<n>" for the rare classes whose attribute
lists differ between objects.

Usage:
    python goschema_gen.py <create_update folder> <output file>
"""
import os
import re
import sys

HEADER_GO = re.compile(r'^#VALUES FOR GOID: (\d+), (.*)$')
HEADER_USING = re.compile(r'^#USING (?:FOR UPDATE )?(\d+),')


def parse(path):
    go_id = name = class_id = None
    attributes = []
    in_using = False
    with open(path, 'r', encoding='latin1') as f:
        for raw in f:
            line = raw.rstrip('\r\n')
            m = HEADER_GO.match(line)
            if m:
                go_id, name = int(m.group(1)), m.group(2).strip()
                continue
            m = HEADER_USING.match(line)
            if m:
                # A few objects list more than one usable class - the first one is used on the wire
                in_using = class_id is None
                if in_using:
                    class_id = int(m.group(1))
                continue
            if line.startswith('#'):
                in_using = False
                continue
            if in_using and line.strip():
                attr_id, attr_name, attr_type, size = line.split(',')
                attributes.append((int(attr_id), attr_name, attr_type, int(size)))
    return go_id, name, class_id, attributes


def main():
    root, output = sys.argv[1], sys.argv[2]
    create_dir = os.path.join(root, 'create', 'allgoids_creation')
    update_dir = os.path.join(root, 'updates', 'updates')

    # classId -> list of distinct (create attrs, update attrs) variants. Almost every class has exactly one
    # variant; the few inconsistent ones get a suffixed key ("3781.1") so every GO keeps its exact lists.
    variants = {}
    gos = []
    for file_name in sorted(os.listdir(create_dir), key=lambda n: int(n.split('.')[0])):
        go_id, name, create_class, create_attrs = parse(os.path.join(create_dir, file_name))
        update_class, update_attrs = None, []
        update_path = os.path.join(update_dir, file_name)
        if os.path.exists(update_path):
            _, _, update_class, update_attrs = parse(update_path)
        if create_class is None:
            continue
        if update_class is not None and update_class != create_class:
            print('WARN go %d uses create class %d but update class %d' % (go_id, create_class, update_class), file=sys.stderr)
        known = variants.setdefault(create_class, [])
        lists = (create_attrs, update_attrs)
        if lists not in known:
            known.append(lists)
            if len(known) > 1:
                print('WARN class %d variant %d (go %d)' % (create_class, len(known) - 1, go_id), file=sys.stderr)
        index = known.index(lists)
        key = str(create_class) if index == 0 else '%d.%d' % (create_class, index)
        gos.append((go_id, key, name))

    with open(output, 'w', encoding='utf-8', newline='\n') as out:
        out.write('# Generated by tools/goschema_gen.py from the gameobjects.gob dump - do not edit\n')
        for class_id in sorted(variants):
            for index, (create_attrs, update_attrs) in enumerate(variants[class_id]):
                key = str(class_id) if index == 0 else '%d.%d' % (class_id, index)
                out.write('CLASS\t%s\n' % key)
                for attr in create_attrs:
                    out.write('C\t%d\t%s\t%s\t%d\n' % attr)
                for attr in update_attrs:
                    out.write('U\t%d\t%s\t%s\t%d\n' % attr)
        for go in gos:
            out.write('GO\t%d\t%s\t%s\n' % go)

    print('classes: %d, gos: %d' % (sum(len(v) for v in variants.values()), len(gos)), file=sys.stderr)


if __name__ == '__main__':
    main()
