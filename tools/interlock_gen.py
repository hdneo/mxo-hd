"""
Builds data/interlock_moves.txt from the interlock database dump (interlock_master.xml, rez 0x24000B8B).

The move id used in the IL combat packets is the 0-based index of the MOVE element in the file
(verified against logged combat packets).

Output (tab separated):
    id  kind  attacker  defender  outcome  duration_ms  flags  group  description
kind:     E = exchange ("XY vs ZW:Outcome"), T = style transition ("Transitions from A:to B"), O = other
attacker/defender: exchange -> style letter + tactic letter (e.g. PD); transition -> from/to style name
    style letters: A aikido, W kungfu, K karate, S self-defense, P pistol, D dual weapons, G sub machine gun,
    R rifle; tactic letters: S speed, P power, D grab, B block
DATA blob of a move: u32 flags, u16 duration in ms.

Usage:
    python interlock_gen.py <interlock_master.xml> <output>
"""
import re
import struct
import sys


def main():
    source, output = sys.argv[1], sys.argv[2]
    text = open(source, encoding='latin1').read()
    rows = []
    group = None
    for m in re.finditer(r'<NAME value= "([^"]*)"|<MOVE children= "\d+">\s*<DATA desc="([^"]*)" blob="([0-9a-fA-F]*)"', text):
        if m.group(1) is not None:
            group = m.group(1)
            continue
        desc, blob = m.group(2), bytes.fromhex(m.group(3))
        flags, duration = (struct.unpack('<IH', blob) if len(blob) == 6 else (0, 0))
        kind, attacker, defender, outcome = 'O', '', '', ''
        e = re.match(r'^([A-Z]{2}) vs ([A-Z]{2}):(.*)$', group)
        t = re.match(r'^Transitions from (.*):to (.*)$', group)
        if e:
            kind, attacker, defender, outcome = 'E', e.group(1), e.group(2), e.group(3)
        elif t:
            kind, attacker, defender = 'T', t.group(1), t.group(2)
        rows.append((len(rows), kind, attacker, defender, outcome, duration, flags, group, desc.replace('\t', ' ')))

    # sanity check: MOVE count must match the number of MOVE elements (moves without DATA would shift ids)
    total = len(re.findall(r'<MOVE children', text))
    if total != len(rows):
        raise SystemExit('found %d MOVE elements but parsed %d moves - ids would be wrong' % (total, len(rows)))

    with open(output, 'w', encoding='utf-8', newline='\n') as out:
        out.write('# Generated by tools/interlock_gen.py from interlock_master.xml - move id = index\n')
        for row in rows:
            out.write('%d\t%s\t%s\t%s\t%s\t%d\t%x\t%s\t%s\n' % row)
    print('%d moves' % len(rows), file=sys.stderr)


if __name__ == '__main__':
    main()
