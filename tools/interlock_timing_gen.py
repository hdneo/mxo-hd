"""
Learns timing templates of interlock exchanges from the packet logs -> data/interlock_timing.txt.

The ILCombatHandler updates contain start offsets, animation durations, flags and damage scales that
depend on the animation data of the moves. They are not derivable from the interlock database alone,
so the most common values the original server sent for every exchange move are used as templates.

Only length prefixed updates are used (admin view "pending create update": 01 00 02 <u16 len> <u16 view>
<update>), they can be found without tracking views and are validated by their length.

Output (tab separated):
    exchange_move  samples  transition_time_a  transition_time_b  unknown3  exchange_start  duration_a
    duration_b  flags  damage_scale_a  damage_scale_b  tail_a1 tail_a2 tail_b1 tail_b2

Usage:
    python interlock_timing_gen.py <corpus from logcorpus.py> <output>
"""
import collections
import struct
import sys

EXCHANGE_FMT = '<BBHHffffffHHIhHHB' + 'II' * 3 + '16sIIHHIIIIII'
EXCHANGE_SIZE = struct.calcsize(EXCHANGE_FMT)


def decode_update(data):
    """returns list of exchange tuples if data is exactly one IL update, else None"""
    if not data or data[0] not in (1, 3):
        return None
    p = 1 + 24 + 4
    if len(data) < p + 4:
        return None
    flags = struct.unpack_from('<I', data, p)[0]
    p += 4
    if flags & ~0x80000003:
        return None
    if flags & 0x80000000:
        p += 4
    p += 4 * bin(flags & 3).count('1')
    if p >= len(data):
        return None
    count = data[p]
    p += 1
    exchanges = []
    for _ in range(count):
        if p + EXCHANGE_SIZE > len(data):
            return None
        exchanges.append(struct.unpack_from(EXCHANGE_FMT, data, p))
        p += EXCHANGE_SIZE
    if data[0] & 2:
        if p >= len(data) or data[p] != 1:
            return None
        p += 25
    return exchanges if p == len(data) else None


def main():
    corpus, output = sys.argv[1], sys.argv[2]
    templates = collections.defaultdict(collections.Counter)
    for line in open(corpus, encoding='utf-8'):
        if line[0] != 'S':
            continue
        data = bytes.fromhex(line[2:].split('\t')[0])
        start = 0
        while True:
            i = data.find(b'\x01\x00\x02', start)
            if i < 0:
                break
            start = i + 1
            if i + 7 > len(data):
                continue
            length = struct.unpack_from('<H', data, i + 3)[0]
            block = data[i + 5:i + 3 + length]
            if len(block) != length - 2 or len(block) < 3:
                continue
            exchanges = decode_update(block[2:])
            if not exchanges:
                continue
            for e in exchanges:
                (role_a, role_b, trans_a, trans_b, ax, ay, az, bx, by, bz, unknown3, rnd, time, start_ofs, dur_a, dur_b,
                 flags, m0, d0, m1, d1, m2, d2, zeros, value_a, value_b, scale_a, scale_b, t1, t2, t3, t4, w1, w2) = e
                if d2 == 0:
                    continue
                templates[m2][(trans_a, trans_b, unknown3, start_ofs, dur_a, dur_b, flags & 0xfc, scale_a, scale_b, t1, t2, t3, t4)] += 1

    with open(output, 'w', encoding='utf-8', newline='\n') as out:
        out.write('# Generated by tools/interlock_timing_gen.py - most common logged timing per exchange move\n')
        for move in sorted(templates):
            template, _ = templates[move].most_common(1)[0]
            out.write('%d\t%d\t%s\n' % (move, sum(templates[move].values()), '\t'.join(str(v) for v in template)))
    print('%d exchange moves with templates' % len(templates), file=sys.stderr)


if __name__ == '__main__':
    main()
